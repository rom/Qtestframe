package ci

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"
)

// ResultsDir is where the jobs of a generated child pipeline write their
// JUnit reports.
const ResultsDir = "qtf-results"

// DefaultCommands are the test commands of the child pipeline's jobs per
// runner. They read $QTF_FILTER (the runner's filter of the selected
// tests), $QTF_TESTS (the keys, space-separated) and write JUnit XML to
// $QTF_RESULTS.
var DefaultCommands = map[string]string{
	"pytest":      `pytest -k "$QTF_FILTER" --junitxml="$QTF_RESULTS/pytest.xml"`,
	"go":          `gotestsum --junitfile "$QTF_RESULTS/go.xml" -- -run "$QTF_FILTER" ./...`,
	"playwright":  `PLAYWRIGHT_JUNIT_OUTPUT_NAME="$QTF_RESULTS/playwright.xml" npx playwright test --grep "$QTF_FILTER" --reporter=junit`,
	"maven":       `mvn -B test -Dtest="$QTF_FILTER" -Dsurefire.failIfNoSpecifiedTests=false; s=$?; cp target/surefire-reports/*.xml "$QTF_RESULTS/" 2>/dev/null; exit $s`,
	RunnerDefault: `echo "No test command for runner $QTF_RUNNER: pass qtestframe select --job $QTF_RUNNER=COMMAND. Tests: $QTF_TESTS"; exit 1`,
}

// filterFormat is the filter a runner's job gets as $QTF_FILTER.
func filterFormat(runner string) string {
	switch runner {
	case "pytest", "go", "playwright", "maven":
		return runner
	case "junit", "gradle":
		return "maven"
	}
	return ""
}

// PipelineOptions configure ChildPipeline.
type PipelineOptions struct {
	// Commands and Images per runner override DefaultCommands and Image.
	Commands map[string]string
	Images   map[string]string
	// Image of the test jobs without one of their own ("" the pipeline's default).
	Image string
	// CLIImage: the image with the qtestframe binary for the final job
	// (default $QTF_CLI_IMAGE).
	CLIImage string
	// RunID: the run created for the selection; else RunName is reported
	// into with --create-run.
	RunID, RunName string
	// ReportArgs are added to qtestframe report, GateArgs to qtestframe
	// gate; NoGate leaves the gate out.
	ReportArgs, GateArgs []string
	NoGate               bool
}

func q(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

// shellQuote quotes s for a POSIX shell (single quotes).
func shellQuote(s string) string {
	if s != "" && strings.IndexFunc(s, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("-_./=:,@%+", r))
	}) < 0 {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'"'"'`) + "'"
}

func shellJoin(args []string) string {
	out := make([]string, len(args))
	for i, a := range args {
		// $VARIABLES stay expandable
		if strings.HasPrefix(a, "$") && !strings.ContainsAny(a, " '\"") {
			out[i] = `"` + a + `"`
		} else {
			out[i] = shellQuote(a)
		}
	}
	return strings.Join(out, " ")
}

// ChildPipeline renders a GitLab child pipeline for the selection: one job
// per runner group with the runner's filter, and a final job (also when
// tests failed) that uploads the JUnit reports with qtestframe report and
// checks the quality gate. A parent job writes it as an artifact and
// triggers it with trigger: include: artifact:.
func (s *Selection) ChildPipeline(o PipelineOptions) (string, error) {
	var b strings.Builder
	b.WriteString("# Generated by qtestframe select --format gitlab-child-pipeline; do not edit.\n")
	fmt.Fprintf(&b, "# Project %s: %d automated test(s) selected", s.Project.Key, len(s.Tests))
	if s.Run != nil {
		fmt.Fprintf(&b, " into run %q", s.Run.Name)
	}
	b.WriteString(".\n")
	b.WriteString("stages: [test, report]\n\n")
	cli := o.CLIImage
	if cli == "" {
		cli = "$QTF_CLI_IMAGE"
	}
	groups := s.Groups()
	if len(groups) == 0 {
		b.WriteString("qtestframe-no-tests:\n  stage: report\n  rules:\n    - when: always\n  image: " + q(cli) + "\n  script:\n    - echo " + q("Qtestframe selected no automated tests for this change.") + "\n")
		return b.String(), nil
	}
	var names []string
	for _, g := range groups {
		cmd := o.Commands[g.Runner]
		if cmd == "" {
			cmd = DefaultCommands[g.Runner]
		}
		if cmd == "" {
			cmd = DefaultCommands[RunnerDefault]
		}
		filter := strings.Join(g.Keys(), " ")
		if f := filterFormat(g.Runner); f != "" {
			var err error
			if filter, err = Filter(f, g.Keys()); err != nil {
				return "", err
			}
		}
		name := "qtestframe-tests:" + g.Runner
		names = append(names, name)
		// rules: jobs without them do not run in the child of a merge
		// request pipeline
		fmt.Fprintf(&b, "%s:\n  stage: test\n  rules:\n    - when: on_success\n", q(name))
		img := o.Images[g.Runner]
		if img == "" {
			img = o.Image
		}
		if img != "" {
			fmt.Fprintf(&b, "  image: %s\n", q(img))
		}
		fmt.Fprintf(&b, "  variables:\n    QTF_RUNNER: %s\n    QTF_TESTS: %s\n    QTF_FILTER: %s\n    QTF_RESULTS: %s\n",
			q(g.Runner), q(strings.Join(g.Keys(), " ")), q(filter), q(ResultsDir))
		b.WriteString("  script:\n    - mkdir -p \"$QTF_RESULTS\"\n")
		fmt.Fprintf(&b, "    - %s\n", q(cmd))
		fmt.Fprintf(&b, "  artifacts:\n    when: always\n    paths: [%s]\n    reports:\n      junit: %s\n\n", q(ResultsDir+"/"), q(ResultsDir+"/*.xml"))
	}
	sort.Strings(names)
	report := []string{"qtestframe", "report"}
	gate := []string{"qtestframe", "gate"}
	if o.RunID != "" {
		report = append(report, "--run-id", o.RunID)
		gate = append(gate, "--run-id", o.RunID)
	} else {
		name := o.RunName
		if name == "" {
			name = "$QTF_RUN"
		}
		report = append(report, "--run", name, "--create-run")
		gate = append(gate, "--run", name)
	}
	report = append(report, "--junit", ResultsDir+"/*.xml")
	report = append(report, o.ReportArgs...)
	gate = append(gate, o.GateArgs...)
	gate = append(gate, "--format", "junit", "--output", "qtf-gate.xml")
	b.WriteString("qtestframe-report:\n  stage: report\n  rules:\n    - when: always\n")
	fmt.Fprintf(&b, "  image: %s\n", q(cli))
	b.WriteString("  needs:\n")
	for _, n := range names {
		fmt.Fprintf(&b, "    - job: %s\n      artifacts: true\n", q(n))
	}
	b.WriteString("  script:\n")
	fmt.Fprintf(&b, "    - %s\n", q(shellJoin(report)))
	if !o.NoGate {
		fmt.Fprintf(&b, "    - %s\n", q(shellJoin(gate)))
		b.WriteString("  artifacts:\n    when: always\n    reports:\n      junit: qtf-gate.xml\n")
	}
	return b.String(), nil
}
