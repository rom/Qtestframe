#!/usr/bin/env bash
# Local development: run the Go backend (SQLite by default) and the Vite dev
# server for the web UI with hot reload. Works on Linux and macOS.
#
#   scripts/dev.sh                 # backend :8080 + web :5173 (open http://localhost:5173)
#   scripts/dev.sh --postgres      # use scripts/dev-postgres.sh instead of SQLite
#   scripts/dev.sh --seed          # load demo data first
#   scripts/dev.sh --backend-only | --web-only
set -euo pipefail

REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
PROG=$(basename "$0")
DATA_DIR=${QTF_DEV_DATA:-$REPO_DIR/data}
PORT=${QTF_DEV_PORT:-8080}
USE_PG=0
SEED=0
RUN_BACKEND=1
RUN_WEB=1
ADMIN_EMAIL=${QTF_DEV_ADMIN_EMAIL:-admin@example.com}
ADMIN_PASSWORD=${QTF_DEV_ADMIN_PASSWORD:-admin-dev-password}

usage() {
	cat <<EOF
Usage: $PROG [options]

Builds ./bin/qtestframe, writes a development config to
$DATA_DIR/dev-config.yaml (plain HTTP on :$PORT, insecure cookies, Landlock
off so the repo-local data dir works), runs migrations and starts:
  backend  http://localhost:$PORT       (API, /healthz, /readyz)
  web      http://localhost:5173        (Vite, proxies /api -> :$PORT)

Options:
  --postgres       use the throw-away PostgreSQL from scripts/dev-postgres.sh
  --seed           run "qtestframe seed-demo" before serving
  --backend-only   do not start Vite
  --web-only       only start Vite (backend running elsewhere)
  --reset          delete the development SQLite database first
  -h, --help       show this help

Bootstrap login: $ADMIN_EMAIL / $ADMIN_PASSWORD
(override with QTF_DEV_ADMIN_EMAIL / QTF_DEV_ADMIN_PASSWORD)
EOF
}

RESET=0
while [ $# -gt 0 ]; do
	case "$1" in
	--postgres) USE_PG=1 ;;
	--seed) SEED=1 ;;
	--backend-only) RUN_WEB=0 ;;
	--web-only) RUN_BACKEND=0 ;;
	--reset) RESET=1 ;;
	-h | --help) usage; exit 0 ;;
	*) echo "$PROG: unknown option: $1" >&2; usage >&2; exit 2 ;;
	esac
	shift
done

need() { command -v "$1" >/dev/null 2>&1 || { echo "$PROG: $1 is required ($2)" >&2; exit 1; }; }

PIDS=""
cleanup() {
	trap - INT TERM EXIT
	for p in $PIDS; do kill "$p" 2>/dev/null || true; done
	wait 2>/dev/null || true
}
trap cleanup INT TERM EXIT

if [ "$RUN_BACKEND" -eq 1 ]; then
	need go "https://go.dev/dl/"
	mkdir -p "$DATA_DIR" "$DATA_DIR/runner" "$REPO_DIR/bin"
	chmod 0700 "$DATA_DIR"

	if [ "$RESET" -eq 1 ]; then rm -f "$DATA_DIR"/dev.db "$DATA_DIR"/dev.db-*; fi

	if [ "$USE_PG" -eq 1 ]; then
		"$REPO_DIR/scripts/dev-postgres.sh" start
		DRIVER=postgres
		DSN=$("$REPO_DIR/scripts/dev-postgres.sh" dsn)
	else
		DRIVER=sqlite
		DSN="$DATA_DIR/dev.db"
	fi

	CONFIG="$DATA_DIR/dev-config.yaml"
	# Regenerated on every start; for local tweaks use QTF_* environment
	# variables (they override the file).
	# The script runner sandbox (Landlock/seccomp) only exists on Linux.
	RUNNER_ENABLED=false
	if [ "$(uname -s)" = Linux ]; then RUNNER_ENABLED=true; fi
	cat >"$CONFIG" <<EOF
# Generated by scripts/dev.sh — DEVELOPMENT ONLY (plain HTTP, weak settings).
server:
  listen: "127.0.0.1:$PORT"
  base_url: "http://localhost:5173"
  hsts: false
database:
  driver: $DRIVER
  dsn: "$DSN"
logging:
  level: debug
  format: text
auth:
  local: true
  session_ttl: 12h
  cookie_secure: false
runner:
  enabled: $RUNNER_ENABLED
  timeout: 30s
  work_dir: "$DATA_DIR/runner"
  sandbox: true
hardening:
  no_new_privs: true
  landlock: false
  seccomp: true
  drop_capabilities: true
bootstrap:
  tenant_slug: default
  tenant_name: "Default"
  admin_email: "$ADMIN_EMAIL"
  admin_password: "$ADMIN_PASSWORD"
EOF
	chmod 0600 "$CONFIG"

	echo "==> building backend"
	(cd "$REPO_DIR" && CGO_ENABLED=0 go build -trimpath -ldflags "-X main.version=dev" -o bin/qtestframe ./cmd/qtestframe)
	echo "==> migrating ($DRIVER)"
	"$REPO_DIR/bin/qtestframe" migrate --config "$CONFIG"
	if [ "$SEED" -eq 1 ]; then
		echo "==> loading demo data"
		QTF_CONFIG="$CONFIG" "$REPO_DIR/bin/qtestframe" seed-demo
	fi
	echo "==> backend on http://127.0.0.1:$PORT"
	"$REPO_DIR/bin/qtestframe" serve --config "$CONFIG" &
	PIDS="$PIDS $!"
fi

if [ "$RUN_WEB" -eq 1 ]; then
	need npm "https://nodejs.org/ (Node 22)"
	if [ ! -d "$REPO_DIR/web/node_modules" ]; then
		echo "==> installing web dependencies"
		(cd "$REPO_DIR/web" && npm ci --no-audit --no-fund)
	fi
	echo "==> web UI on http://localhost:5173"
	(cd "$REPO_DIR/web" && exec npm run dev) &
	PIDS="$PIDS $!"
fi

echo "==> login: $ADMIN_EMAIL / $ADMIN_PASSWORD   (Ctrl-C stops everything)"
# bash 3.2 (macOS) has no `wait -n`: poll until one child exits.
while :; do
	for p in $PIDS; do
		if ! kill -0 "$p" 2>/dev/null; then
			wait "$p" 2>/dev/null && rc=0 || rc=$?
			echo "$PROG: process $p exited (status $rc); stopping" >&2
			exit "$rc"
		fi
	done
	sleep 1
done
